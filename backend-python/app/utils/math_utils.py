import numpy as np


def cosine_similarity(a, b):
    """Calcula a similaridade de cosseno entre dois vetores, com proteção contra norma zero."""
    a = np.array(a)
    b = np.array(b)
    norm_a = np.linalg.norm(a)
    norm_b = np.linalg.norm(b)
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return float(np.dot(a, b) / (norm_a * norm_b))